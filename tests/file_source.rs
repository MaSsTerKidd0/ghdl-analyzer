//! Integration tests: open the sample files in `examples/` through `FileSource`
//! and check the hierarchy and some known values.

use std::io::Write;
use std::path::PathBuf;

use ghdl_analyzer::model::file_source::FileSource;
use ghdl_analyzer::model::{SegmentValue, SignalId, SignalKind, Value, WaveSource};

fn example(name: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("examples")
        .join(name)
}

fn find(source: &dyn WaveSource, path: &str) -> SignalId {
    source
        .signals()
        .iter()
        .position(|s| s.path == path)
        .unwrap_or_else(|| {
            let all: Vec<_> = source.signals().iter().map(|s| &s.path).collect();
            panic!("signal {path} not found; have {all:?}")
        })
}

fn bits(s: &str) -> Option<Value> {
    Some(Value::Bits(s.to_string()))
}

#[test]
fn hand_written_vcd() {
    let mut src = FileSource::open(example("counter.vcd")).unwrap();
    assert_eq!(src.hierarchy().len(), 1);
    let top = &src.hierarchy()[0];
    assert_eq!(top.name, "counter_tb");
    assert_eq!(top.scopes[0].name, "dut");
    assert_eq!(src.time_range(), (0, 90));
    assert_eq!(src.timescale().exponent, -9);
    assert_eq!(src.timescale().format(25), "25 ns");

    let clk = find(&src, "counter_tb.clk");
    let count = find(&src, "counter_tb.count[7:0]");
    let oe = find(&src, "counter_tb.data_bus_oe");
    assert_eq!(src.signals()[clk].kind, SignalKind::Bit);
    assert_eq!(src.signals()[count].kind, SignalKind::Vector(8));

    src.load(&[clk, count, oe]);
    assert_eq!(src.value_at(clk, 0), bits("0"));
    assert_eq!(src.value_at(clk, 7), bits("1"));
    assert_eq!(src.value_at(count, 3), bits("xxxxxxxx"));
    assert_eq!(src.value_at(count, 40), bits("00000010"));
    assert_eq!(src.value_at(oe, 0), bits("z"));
    assert_eq!(src.value_at(oe, 62), bits("x"));

    assert_eq!(src.next_change(clk, 5), Some(10));
    assert_eq!(src.prev_change(clk, 10), Some(5));
    assert_eq!(src.next_change(count, 65), None);
    assert_eq!(src.prev_change(count, 0), None);
}

#[test]
fn segments_cover_window() {
    let mut src = FileSource::open(example("counter.vcd")).unwrap();
    let count = find(&src, "counter_tb.count[7:0]");
    src.load(&[count]);

    // The window starts at 30: the first segment is the value active at 30 (set at 25).
    let segs = src.segments(count, 30, 50, 1);
    let starts: Vec<_> = segs.iter().map(|s| s.start).collect();
    assert_eq!(starts, vec![25, 35, 45]);
    assert_eq!(
        segs[1].value,
        SegmentValue::Stable(Value::Bits("00000010".into()))
    );
}

#[test]
fn dense_changes_are_merged() {
    // A clock with 100 000 edges: zoomed out, the viewer must not get 100 000 segments.
    let dir = std::env::temp_dir().join(format!("ghdl-analyzer-test-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let path = dir.join("fast.vcd");
    let mut f = std::io::BufWriter::new(std::fs::File::create(&path).unwrap());
    writeln!(f, "$timescale 1 ps $end\n$scope module top $end\n$var wire 1 ! clk $end\n$upscope $end\n$enddefinitions $end").unwrap();
    for i in 0..100_000u64 {
        writeln!(f, "#{}\n{}!", i * 10, i % 2).unwrap();
    }
    drop(f);

    let mut src = FileSource::open(&path).unwrap();
    let clk = find(&src, "top.clk");
    src.load(&[clk]);

    // 1 000 000 ps across 1 000 pixels: 1 000 ps per pixel, i.e. 100 edges per pixel.
    let segs = src.segments(clk, 0, 1_000_000, 1_000);
    assert!(segs.len() <= 2_100, "got {} segments", segs.len());
    assert!(segs.iter().any(|s| s.value == SegmentValue::Dense));

    // Zoomed in, every edge is its own segment.
    let segs = src.segments(clk, 0, 100, 1);
    assert_eq!(segs.len(), 11);
    assert!(
        segs.iter()
            .all(|s| matches!(s.value, SegmentValue::Stable(_)))
    );
    std::fs::remove_dir_all(&dir).ok();
}

/// Files generated by GHDL itself (see examples/vhdl/generate.sh).
#[test]
fn ghdl_generated_files() {
    for file in ["counter_tb.ghw", "counter_tb.fst", "counter_tb.vcd"] {
        let mut src = FileSource::open(example(file)).unwrap();
        let clk = find(&src, "counter_tb.clk");
        let count = src
            .signals()
            .iter()
            .position(|s| s.path.starts_with("counter_tb.count"))
            .unwrap_or_else(|| panic!("{file}: no count signal"));
        src.load(&[clk, count]);

        // GHDL writes femtoseconds.
        assert_eq!(src.timescale().format(5_000_000), "5 ns", "{file}");
        assert_eq!(src.value_at(clk, 0), bits("0"), "{file}");
        assert_eq!(src.value_at(clk, 5_000_000), bits("1"), "{file}");
        // Counting starts after reset (12 ns) and enable (22 ns): first increment at 25 ns.
        assert_eq!(src.value_at(count, 26_000_000), bits("00000001"), "{file}");
        assert_eq!(src.value_at(count, 0), bits("uuuuuuuu"), "{file}");
    }
}

#[test]
fn ghw_enumeration_names() {
    // Only GHW keeps the VHDL enumeration type; the state machine shows its literal names.
    let mut src = FileSource::open(example("counter_tb.ghw")).unwrap();
    let state = find(&src, "counter_tb.state");
    assert_eq!(src.signals()[state].kind, SignalKind::Enum);
    src.load(&[state]);
    assert_eq!(src.value_at(state, 0), Some(Value::Text("idle".into())));
    assert_eq!(
        src.value_at(state, 30_000_000),
        Some(Value::Text("counting".into()))
    );
}

#[test]
fn missing_file_is_an_error() {
    let err = FileSource::open(example("does-not-exist.vcd"))
        .err()
        .unwrap();
    assert!(err.to_string().contains("does-not-exist.vcd"));
}
